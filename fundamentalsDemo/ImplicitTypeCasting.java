package fundamentalsDemo;

public class ImplicitTypeCasting {
	
	public static void main(String[] args)
	{
		byte b = 100;
		short s= b;
		
		int i = s;
		
		long l= i;
		
		long ll= s;
		int ii = b;
		
		
		System.out.println(s);
		System.out.println(ll);
		System.out.println(i);
		
		float f = 3354.14f;
		double d = f;
		
		System.out.println(d);
		
		
	}

}
